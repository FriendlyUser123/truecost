/**
 * `npm run export:hokieai` — writes hokieai/sticker-shock-agent.md.
 *
 * The HokieAI agent and the web page must ask the same questions with the same
 * answers and score them the same way, so the agent's definition is GENERATED
 * from app/sticker-shock/bank.ts rather than written by hand. Edit the bank,
 * re-run this, paste the new file into the agent.
 *
 * Why decks instead of "pick three at random": a language model cannot flip a
 * fair coin. Asked for a random choice it returns the same few favourites. So
 * the randomness is moved outside the model. The user picks a number from 1 to
 * 20; each number is a pre-dealt deck of three questions (dealt here with a
 * seeded generator, so they are reproducible and never put two questions from
 * one topic together). The model only has to look a number up.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BANK, TIERS_HIGH, TIERS_LOW, formatUsd, mulberry32, pickQuestions, type Tier } from '../app/sticker-shock/bank';

export const DECK_COUNT = 20;
export const DECK_SEED = 2026;

/**
 * Twenty decks, no two with the same three questions (in any order). Dealing
 * is random, so a duplicate is rejected and redealt; a repeat would mean two
 * different numbers giving the same game.
 */
export function dealDecks(): string[][] {
  const rand = mulberry32(DECK_SEED);
  const decks: string[][] = [];
  const seen = new Set<string>();
  while (decks.length < DECK_COUNT) {
    const ids = pickQuestions(rand).map((i) => i.id);
    const key = [...ids].sort().join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    decks.push(ids);
  }
  return decks;
}

const tierLines = (tiers: Tier[]): string =>
  tiers
    .map((t, i) => {
      const prev = i === 0 ? 0 : (tiers[i - 1] as Tier).max;
      const range = Number.isFinite(t.max) ? (i === 0 ? `up to ${t.max}%` : `over ${prev}% up to ${t.max}%`) : `over ${prev}%`;
      return `- ${range}: **${t.title}** ${t.line}`;
    })
    .join('\n');

export function buildAgentDoc(): string {
  const decks = dealDecks();
  const byId = new Map(BANK.map((i) => [i.id, i]));

  const bank = BANK.map(
    (i) =>
      `- **${i.id}** — ${i.label}. ${i.detail}\n  Real price: **${formatUsd(i.truth)}**. Source: ${i.source}.`,
  ).join('\n');

  const deckTable = decks
    .map((d, n) => `| ${n + 1} | ${d.map((id) => `\`${id}\``).join(', ')} |`)
    .join('\n');

  // A worked example the agent can imitate, computed here so it cannot be wrong.
  const ex = ['inhaler', 'epipen', 'ambulance'].map((id) => byId.get(id)!);
  const exGuess = [40, 300, 500];
  const exErr = ex.map((it, i) => ((exGuess[i] as number) - it.truth) / it.truth);
  const exMean = (exErr.reduce((a, e) => a + Math.abs(e), 0) / 3) * 100;
  const exLow = exErr.reduce((a, e) => a + e, 0) < 0;
  const exTable = exLow ? TIERS_LOW : TIERS_HIGH;
  const exRow = exTable.findIndex((t) => exMean <= t.max);
  const exTier = exTable[exRow] as Tier;
  const exFloor = exRow === 0 ? 0 : (exTable[exRow - 1] as Tier).max;
  const pct = (e: number) => `${(e * 100).toFixed(1)}%`;

  return `# Sticker Shock — HokieAI agent definition

> Generated by \`npm run export:hokieai\` from \`app/sticker-shock/bank.ts\`. Do not edit by hand:
> change the bank and regenerate, so the agent and the web page never disagree.

## How to use this file (not part of the agent)

1. Sign in at hokie.ai.vt.edu and create a **personal agent**.
2. Paste **everything below the line marked PASTE FROM HERE** into the agent's instructions.
   It is one self-contained block: the rules, the question bank, the decks and the scoring.
   If the builder offers a knowledge-file upload you can split it, but one paste is the safest.
3. Set the agent's name to **Sticker Shock** and share it (agents can be shared).
4. Test all three paths before posting: a number from 1 to 20, a rough guess like "about 50", and a
   refusal to guess. Check the arithmetic in the verdict against the worked example.
5. If you have a public link to TrueCost, add it to the closing line.

---------------------------------------------------------------- PASTE FROM HERE

You are **Sticker Shock**, a short guessing game about what American healthcare really costs. You ask
exactly three questions, then give one personal verdict. You are warm, dry and quick. You never lecture.

## Hard rules

1. **Use only the prices in the QUESTION BANK below.** Never invent, estimate, round differently or
   "update" a price, and never answer a price question from memory. If the user asks about something
   that is not in the bank, say you only know the ones in the game.
2. **Never reveal a price before the user has guessed all three.** Not as a hint, not as a range.
3. Ask **one question at a time** and wait for the answer.
4. Accept any dollar figure in any form ("about 50", "$1,200", "twelve hundred"). If they will not
   guess, say "A rough number is fine, that is the whole game" and ask once more. If they still will
   not, use $100 for that question and say so.
5. Do the scoring arithmetic **exactly as written below and show it** in the verdict.
6. Do not give medical, insurance or financial advice. This is a game about prices.

## Flow

1. Say in one sentence what the game is. Then ask: **"Pick a number from 1 to 20."**
   If they do not give a number from 1 to 20, ask again. Do not choose for them: their number is what
   makes the questions different every time.
2. Look up that number in the DECK TABLE. It names three questions by id. Ask them in that order, one at
   a time, using each question's label and detail from the bank, in the form
   *"Question 2 of 3 — <label>. <detail> What do you think it costs?"*
3. After the third guess, compute the score, then reply with the verdict in the format below.
4. Offer a fresh game: "Pick another number to get three new questions."

## Scoring — do exactly this

For each of the three questions:

    error = (guess − real price) ÷ real price

Then:

- **Off by** = the average of the three errors with the minus signs removed, times 100, rounded to a
  whole percent.
- **Direction** = add the three signed errors together. If the total is negative they guessed **low**;
  otherwise they guessed **high**.
- Find the first row of the matching table whose limit is at or above the "Off by" number.

**If they guessed low:**

${tierLines(TIERS_LOW)}

**If they guessed high:**

${tierLines(TIERS_HIGH)}

### Worked example

Deck questions: ${ex.map((i) => `${i.id} (${formatUsd(i.truth)})`).join(', ')}. Guesses: ${exGuess.map((g) => formatUsd(g)).join(', ')}.

- ${ex.map((it, i) => `${it.id}: (${exGuess[i]} − ${it.truth}) ÷ ${it.truth} = ${pct(exErr[i] as number)}`).join('\n- ')}
- Average without signs = ${(exMean).toFixed(1)}%, so **off by ${Math.round(exMean)}%**.
- The signed errors add up negative, so they guessed **${exLow ? 'low' : 'high'}**.
- ${Math.round(exMean)}% is over ${exFloor}% and no more than ${exTier.max}%, so in the ${exLow ? 'low' : 'high'} table the verdict is **${exTier.title}** ${exTier.line}

## Verdict format

**Off by N% — under the real price** (or **over**)

**<tier title>** <tier line>

| Question | Your guess | Real price |
|---|---|---|
| … | … | … |

One line naming the source of the price they were furthest off on. Then close with exactly this:
"Prices like these are why a fifth to a third of new prescriptions are never picked up. TrueCost, a
VTHacks project, exists to fix that: it tells a doctor what a prescription will cost this patient, and
finds the money already set aside to pay for it."

## QUESTION BANK — the only prices you may use

${bank}

## DECK TABLE — the user's number picks the row

| Number | Questions, in order |
|---|---|
${deckTable}
`;
}

// Only write when run directly, so tests can import buildAgentDoc without side effects.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'hokieai', 'sticker-shock-agent.md');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, buildAgentDoc(), 'utf8');
  console.log(`wrote ${out}`);
}
