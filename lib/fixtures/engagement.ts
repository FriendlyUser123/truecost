import type { EngagementChannel, EngagementEvent } from '../ready/types';

/**
 * Four years of one prescriber's engagement archive.
 *
 * This stands in for the Impiricus asset: 1M+ opted-in HCPs, four to five
 * years of per-physician sends, opens and replies. It is the only input from
 * which a *measured* saturation point can be computed, so it has to be honest
 * about two things a hand-waved fixture usually gets wrong.
 *
 * 1. PHARMA ENGAGEMENT IS SPARSE. A physician sees single-digit touches a
 *    month, not dozens a day. This archive averages 9.6 sends/month across
 *    208 weeks — 461 events total. A denser fixture would make the saturation
 *    point trivially large and the whole rationing argument free.
 *
 * 2. SATURATION HAS TO BE IN THE DATA, NOT IN THE CONSTANT. `saturationPoint`
 *    is *measured* by lib/ready/attention.ts, not declared here. For that to
 *    mean anything, weeks with many sends must actually open worse. Two
 *    mechanisms produce that here, and both are mechanisms a real inbox has:
 *      - WEEK_BASE: the more a week asks for, the less each touch is worth.
 *      - carry-over fatigue: a heavy week depresses the *following* three
 *        weeks too, which is what makes attention debt measurable at all.
 *    The archive lands the measured saturation point at 4. Nobody typed a 4.
 *
 * Everything is generated by an explicit LCG from a fixed seed. No
 * Math.random, no Date.now — the numbers on screen at 9 AM are the numbers we
 * rehearsed, on any machine.
 */

export const PRESCRIBER_ID = 'npi-1487203955';
export const PRESCRIBER_NAME = 'Dr. R. Whitfield';
export const PRESCRIBER_SPECIALTY = 'Internal Medicine';
export const PRESCRIBER_CITY = 'Roanoke, VA';

/** A Sunday. Week w runs ARCHIVE_START + 7w .. +7w+6. */
export const ARCHIVE_START = '2022-09-18';
/** Weeks 0..207 end 2026-09-12; the week of DEMO_TODAY is appended separately. */
export const ARCHIVE_WEEKS = 208;

const MS_DAY = 86_400_000;

/**
 * Numerical Recipes LCG. Seeded once, drawn in a fixed order, so the archive
 * is byte-identical on every run. If this is ever replaced with Math.random
 * the saturation point moves and the demo stops being reproducible.
 */
function lcg(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

/**
 * Sends per week across one year, starting mid-September. Fifty-two entries,
 * shaped like a real pharma calendar: a heavy fall launch season, a holiday
 * blackout, a spring push, and a thin summer.
 *
 * The multiset is the load-bearing part. Over four years it gives
 *   0 sends: 16 weeks | 1: 48 | 2: 68 | 3: 44 | 4: 20 | 5: 8 | 6: 4
 * which is what puts the measured saturation point at 4 rather than 3 or 5.
 */
const YEAR_SHAPE: readonly number[] = [
  // Sep–Dec: fall campaign season
  2, 3, 1, 2, 4, 3, 2, 1, 3, 2, 5, 3,
  // Dec–Mar: holiday blackout, then a slow restart
  2, 1, 0, 1, 2, 3, 2, 4, 1, 2, 3, 0,
  // Mar–Jun: spring push, one genuinely abusive week
  3, 2, 4, 1, 2, 1, 3, 2, 6, 3, 2, 1,
  // Jun–Sep: summer thin, one late-August burst
  2, 0, 1, 2, 3, 1, 4, 2, 1, 5, 2, 3,
  0, 1, 2, 4,
];

/**
 * Per-year index swaps applied to YEAR_SHAPE. Swapping preserves the multiset
 * exactly — so the saturation arithmetic above still holds — while stopping
 * four identical years from showing up in the rendered archive.
 */
const YEAR_SWAPS: readonly (readonly (readonly [number, number])[])[] = [
  [],
  [
    [3, 29],
    [11, 40],
    [22, 47],
  ],
  [
    [1, 18],
    [7, 33],
    [25, 44],
  ],
  [
    [5, 20],
    [14, 38],
    [30, 50],
  ],
];

/**
 * The fourteen clock slots a marketing automation platform actually fires
 * into. Concentrating sends here (rather than scattering them over 168
 * buckets) is both realistic and necessary: with 461 events, a uniform
 * scatter leaves every hour-of-week bucket under the 8-send floor and
 * `bestHourOfWeek` becomes unanswerable.
 *
 * `lift` is how much better this slot opens than the average slot. Tue 07:00
 * wins by a wide margin — bucket 2*24+7 = 55.
 */
type SendSlot = readonly [dayOfWeek: number, hour: number, lift: number];

const SEND_SLOTS: readonly SendSlot[] = [
  [1, 7, 1.1], // Mon 07:00 — pre-clinic inbox sweep
  [1, 12, 0.95], // Mon 12:00 — lunch, competing with everything else
  [2, 6, 1.05],
  [2, 7, 1.35], // Tue 07:00 — his hour
  [2, 12, 0.9],
  [3, 7, 1.15],
  [3, 13, 0.85],
  [4, 6, 1.0],
  [4, 7, 1.2],
  [4, 12, 0.88],
  [4, 18, 0.6], // Thu 18:00 — after clinic, opened tomorrow if at all
  [5, 7, 1.05],
  [5, 12, 0.72],
  [6, 9, 0.55], // Sat 09:00 — sent because a campaign calendar said so
];

/** Open probability floor for a week of n sends, before slot and fatigue. */
const WEEK_BASE: readonly number[] = [0, 0.78, 0.7, 0.53, 0.3, 0.24, 0.19];

/** Each additional touch inside the same week is worth 10% less than the last. */
const WITHIN_WEEK_DECAY = 0.1;

const CHANNELS: readonly (readonly [EngagementChannel, number, number])[] = [
  // [channel, cumulative share, open multiplier]
  ['email', 0.7, 1.0],
  ['in-app', 0.88, 1.12],
  ['portal', 0.97, 0.85],
  ['fax', 1.0, 0.35], // a fax is "opened" only when somebody walks to the machine
];

/** Probability a touch draws a reply, conditional on having been opened. */
const REPLY_GIVEN_OPEN = 0.34;

/**
 * Fatigue carried into the next week. A week with u uncorroborated sends adds
 * 0.02 per send past the first and decays 40% a week, so a six-send blast is
 * still costing opens three weeks later. This is the mechanism that makes
 * `debtPerUncorroboratedSend` a measurement rather than an assertion.
 */
const FATIGUE_DECAY = 0.6;
const FATIGUE_PER_EXCESS_SEND = 0.02;
const FATIGUE_CAP = 0.35;

function isoAt(startISO: string, dayOffset: number, hour: number): string {
  const t = new Date(`${startISO}T00:00:00Z`).getTime() + dayOffset * MS_DAY + hour * 3_600_000;
  return `${new Date(t).toISOString().slice(0, 16)}:00Z`;
}

function weeklyPlan(): number[] {
  const out: number[] = [];
  for (let year = 0; year < 4; year++) {
    const row = [...YEAR_SHAPE];
    for (const [i, j] of YEAR_SWAPS[year] ?? []) {
      const a = row[i] as number;
      row[i] = row[j] as number;
      row[j] = a;
    }
    out.push(...row);
  }
  return out;
}

function build(): EngagementEvent[] {
  const rnd = lcg(0x5eed_1487);
  const plan = weeklyPlan();
  const events: EngagementEvent[] = [];
  let fatigue = 0;

  for (let w = 0; w < ARCHIVE_WEEKS; w++) {
    const n = plan[w] ?? 0;
    if (n === 0) {
      fatigue *= FATIGUE_DECAY;
      continue;
    }

    const weekStart = new Date(new Date(`${ARCHIVE_START}T00:00:00Z`).getTime() + w * 7 * MS_DAY)
      .toISOString()
      .slice(0, 10);

    // Pick n distinct slots by walking the table in steps of 5 (coprime with
    // 14, so no repeats), from a rotation the LCG chooses. Then fire them in
    // clock order, because the within-week decay is about *sequence*.
    const offset = Math.floor(rnd() * SEND_SLOTS.length);
    const picked: SendSlot[] = [];
    for (let j = 0; j < n; j++) {
      picked.push(SEND_SLOTS[(offset + j * 5) % SEND_SLOTS.length] as SendSlot);
    }
    picked.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

    let uncorroborated = 0;

    for (let i = 0; i < picked.length; i++) {
      const [dow, hour, lift] = picked[i] as SendSlot;

      const cu = rnd();
      const row = CHANNELS.find((c) => cu <= c[1]) ?? CHANNELS[0];
      const [channel, , channelLift] = row as readonly [EngagementChannel, number, number];

      // Only quiet weeks carried a second corroborating source historically;
      // the blasts are exactly the sends nobody could second-source.
      const corroborated = n <= 2 && rnd() < 0.35;
      if (!corroborated) uncorroborated++;

      const base = WEEK_BASE[n] ?? 0.1;
      const p = base * (1 - WITHIN_WEEK_DECAY * i) * lift * channelLift * (1 - fatigue);
      const opened = rnd() < p;

      // Latency is heavily right-skewed: most opens happen inside the hour,
      // a long tail lands the next morning. u^5 gives a median near an hour.
      const lu = rnd();
      const openedAfterMin = opened ? 5 + Math.floor(2000 * lu ** 5) : null;
      const replied = opened && rnd() < REPLY_GIVEN_OPEN;

      events.push({
        sentAt: isoAt(weekStart, dow, hour),
        channel,
        opened,
        openedAfterMin,
        replied,
        corroborated,
      });
    }

    fatigue = Math.min(
      FATIGUE_CAP,
      fatigue * FATIGUE_DECAY + FATIGUE_PER_EXCESS_SEND * Math.max(0, uncorroborated - 1),
    );
  }

  // The current week (2026-09-13 .. 2026-09-19) already holds one send. It is
  // why the board opens at 3 slots of 4 rather than 4 of 4.
  events.push({
    sentAt: '2026-09-15T07:00:00Z',
    channel: 'in-app',
    opened: true,
    openedAfterMin: 41,
    replied: false,
    corroborated: true,
  });

  return events;
}

export const ENGAGEMENT_HISTORY: EngagementEvent[] = build();
